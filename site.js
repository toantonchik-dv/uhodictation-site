function getPageKey() {
  return document.body.dataset.page || "landing";
}

function getDictionary(language) {
  const pageKey = getPageKey();
  return SITE_TRANSLATIONS[pageKey]?.[language] || SITE_TRANSLATIONS[pageKey]?.en || {};
}

function applyTranslations(language) {
  const dictionary = getDictionary(language);

  document.documentElement.lang = language === "uk" ? "uk" : "en";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const key = node.dataset.i18nHtml;
    if (dictionary[key]) {
      node.innerHTML = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      node.setAttribute("placeholder", dictionary[key]);
    }
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === language);
  });
}

function setLanguage(language) {
  localStorage.setItem("uho_site_language", language);
  applyTranslations(language);
}

function getLanguage() {
  const saved = localStorage.getItem("uho_site_language");
  return saved === "uk" ? "uk" : "en";
}

function initLanguageSwitcher() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.lang));
  });

  applyTranslations(getLanguage());
}

window.UHOI18N = {
  getLanguage,
  setLanguage,
};

initLanguageSwitcher();
